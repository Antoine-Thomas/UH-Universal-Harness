"""Desktop shortcut for the web UI (``uh install-shortcut``, Windows only).

One double-click on the desktop, and the UI is up - for people who will never
open a terminal. Three files, no admin rights, no auto-start:

* ``uh-web.ps1`` in ``$UH_HOME`` - the launcher. It prints a banner in the
  Searching Murphy colours and runs ``uh web --app`` (a chromeless Edge/Chrome
  window); if ``uh`` is not on PATH it says so and waits, instead of flashing a
  window that disappears;
* ``uh-web.ico`` in ``$UH_HOME`` - a gold "UH" monogram on ink, generated here
  (zlib-wrapped PNG inside ICO, standard library only: no new dependency, no
  binary asset to keep in sync with the colours);
* ``UH web.lnk`` on the Desktop, created through ``WScript.Shell``.

Colours are the site's: ``#284543`` ink, ``#fdc502`` accent.

Why a ``.ps1`` at all? A ``.lnk`` cannot target a ``.ps1`` directly - Windows
would open it in Notepad - so the shortcut targets ``powershell.exe`` with
``-File``. ``-ExecutionPolicy Bypass`` is scoped to this one invocation: the
script is local, never downloaded, and asking a user to change a machine-wide
policy for a shortcut is not acceptable.

The exact hexes need 24-bit colour, which needs virtual-terminal processing.
The script turns it on through a five-line ``Add-Type``; when that fails (old
console, restricted policy) it falls back to the nearest ``Write-Host`` colours
and still prints the hexes as text.
"""

from __future__ import annotations

import os
import struct
import subprocess
import sys
import zlib
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Optional, Sequence

INK = "#284543"
ACCENT = "#fdc502"
INK_RGB = (0x28, 0x45, 0x43)
ACCENT_RGB = (0xFD, 0xC5, 0x02)

SCRIPT_NAME = "uh-web.ps1"
ICON_NAME = "uh-web.ico"
LINK_NAME = "UH web.lnk"
LINK_DESCRIPTION = "UH - Universal Harness web UI"

#: Runner seam: tests pass a fake instead of starting PowerShell.
Runner = Callable[[str], str]


class ShortcutError(RuntimeError):
    """The shortcut could not be created. The message is user-facing."""


# --------------------------------------------------------------------------- #
# environment
# --------------------------------------------------------------------------- #
def windows() -> bool:
    """True on Windows; the feature is refused everywhere else."""
    return sys.platform.startswith("win")


def _powershell() -> Path:
    root = os.environ.get("SystemRoot") or r"C:\Windows"
    return Path(root) / "System32" / "WindowsPowerShell" / "v1.0" / "powershell.exe"


def home_directory() -> Path:
    """``$UH_HOME``, the same folder memory and config already use."""
    from .toolsets.memory import uh_home

    return uh_home()


def desktop_directory() -> Path:
    """The real Desktop, following a OneDrive redirect when there is one.

    ``UH_DESKTOP`` overrides it (tests, and the rare user whose Desktop is
    somewhere else); otherwise the shell's usual locations are probed rather
    than assumed, because ``%USERPROFILE%\\Desktop`` is empty on a redirected
    profile.
    """
    override = (os.environ.get("UH_DESKTOP") or "").strip()
    if override:
        return Path(override).expanduser()
    home = Path.home()
    candidates = sorted(p for p in home.glob("OneDrive*/Desktop") if p.is_dir())
    candidates.append(home / "Desktop")
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return home / "Desktop"


# --------------------------------------------------------------------------- #
# the launcher script
# --------------------------------------------------------------------------- #
BANNER = (
    "+-----------------------------------------------+",
    "|  UH  -  Universal Harness                     |",
    "|  Searching Murphy   ink #284543  accent #fdc502|",
    "+-----------------------------------------------+",
)


def script_text() -> str:
    """The PowerShell launcher, ASCII only (PowerShell 5.1 reads no BOM as ANSI)."""
    return "\n".join(
        [
            "# UH web UI - generated by `uh install-shortcut`; safe to delete.",
            "# The shortcut starts this script with -WindowStyle Hidden: the browser",
            "# is the interface, and a console window on top of it is noise. Anything",
            "# that fails is written to uh-web.log next to this file and shown in a",
            "# MessageBox, because a hidden window cannot show a message.",
            "$ErrorActionPreference = 'Continue'",
            "$log = Join-Path $PSScriptRoot 'uh-web.log'",
            "",
            "function Write-UhLog($line) {",
            "  try {",
            "    \"$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') $line\" |",
            "      Out-File -FilePath $log -Append -Encoding utf8 -ErrorAction Stop",
            "  } catch { }",
            "}",
            "",
            "function Show-UhError($text) {",
            "  Write-UhLog \"error: $text\"",
            "  Write-Host $text -ForegroundColor Red",
            "  try {",
            "    Add-Type -AssemblyName System.Windows.Forms -ErrorAction Stop",
            "    [System.Windows.Forms.MessageBox]::Show($text, 'UH web', 'OK', 'Warning') | Out-Null",
            "  } catch { }",
            "}",
            "",
            "$esc = [char]27",
            "",
            "# 24-bit colour when the console supports it; plain text when it does not.",
            "try {",
            "  if (-not ('UhVt' -as [type])) {",
            "    Add-Type -ErrorAction Stop -TypeDefinition @'",
            "using System;",
            "using System.Runtime.InteropServices;",
            "public static class UhVt {",
            "  [DllImport(\"kernel32.dll\", SetLastError = true)] static extern IntPtr GetStdHandle(int h);",
            "  [DllImport(\"kernel32.dll\", SetLastError = true)] static extern bool GetConsoleMode(IntPtr h, out uint m);",
            "  [DllImport(\"kernel32.dll\", SetLastError = true)] static extern bool SetConsoleMode(IntPtr h, uint m);",
            "  public static void Enable() {",
            "    IntPtr handle = GetStdHandle(-11); uint mode;",
            "    if (GetConsoleMode(handle, out mode)) { SetConsoleMode(handle, mode | 0x0004); }",
            "  }",
            "}",
            "'@",
            "  }",
            "  [UhVt]::Enable()",
            "  $ink = \"$esc[38;2;40;69;67m\"",
            "  $accent = \"$esc[38;2;253;197;2m\"",
            "  $reset = \"$esc[0m\"",
            "} catch {",
            "  $ink = ''; $accent = ''; $reset = ''",
            "}",
            "",
            "Write-Host ($accent + '" + BANNER[0] + "')",
            "Write-Host ($accent + '" + BANNER[1] + "')",
            "Write-Host ($ink + '" + BANNER[2] + "')",
            "Write-Host ($accent + '" + BANNER[3] + "' + $reset)",
            "Write-Host ''",
            "",
            "$uh = Get-Command uh -ErrorAction SilentlyContinue",
            "if (-not $uh) {",
            "  Show-UhError 'uh is not on PATH. Install it with: pip install uh-harness, then run this shortcut again.'",
            "  exit 1",
            "}",
            "",
            "Write-UhLog 'starting uh web --app'",
            # --app: the window has no tab bar and no address bar, which is what
            # makes the shortcut feel like an application and not a bookmark.
            # Without Edge or Chrome, `uh web` says so and opens a normal tab.
            "& $uh.Source web --app @args",
            "if ($LASTEXITCODE -ne 0) {",
            "  # A bare exit code tells nobody what to do next: name the two causes",
            "  # that account for almost every failure, then the file with the detail.",
            "  $nl = [Environment]::NewLine",
            "  $text = 'UH failed to start (exit code ' + $LASTEXITCODE + ').' + $nl + $nl +",
            "          'Common causes: another UH is already running, or the second ' +",
            "          'brain (UHB) could not start.' + $nl +",
            "          'Log: ' + $log",
            "  Show-UhError $text",
            "} else {",
            "  Write-UhLog 'uh web stopped cleanly'",
            "}",
            "exit $LASTEXITCODE",
            "",
        ]
    )


# --------------------------------------------------------------------------- #
# icon (zlib PNG inside an ICO, no dependency)
# --------------------------------------------------------------------------- #
SIZE = 256
#: One entry per size Windows asks for: the taskbar and the desktop read 16-48,
#: the icon dialog reads 256. A single 256 entry gets downsampled by the shell
#: and the two bars of the monogram blur at 16 px.
ICON_SIZES = (16, 32, 48, 256)

#: The monogram: two block letters, "U" then "H", in the tile's inner box.
GLYPH_BOX = (0.115, 0.250, 0.885, 0.760)
STROKE = 0.088  # bar thickness, as a fraction of the tile
GAP = 0.105  # space between the two letters


def _blend(base: tuple[int, int, int], amount: float) -> tuple[int, int, int]:
    """Lighten (amount > 0) or darken (amount < 0) a colour, clipped."""
    channel: list[int] = []
    for value in base:
        raw = value + (255 - value) * amount if amount >= 0 else value * (1.0 + amount)
        channel.append(max(0, min(255, int(round(raw)))))
    return (channel[0], channel[1], channel[2])


def _mix(
    start: tuple[int, int, int], end: tuple[int, int, int], weight: float
) -> tuple[int, int, int]:
    """Linear interpolation between two colours, per channel."""
    return (
        int(round(start[0] + (end[0] - start[0]) * weight)),
        int(round(start[1] + (end[1] - start[1]) * weight)),
        int(round(start[2] + (end[2] - start[2]) * weight)),
    )


def _bar(x: float, y: float, x0: float, y0: float, x1: float, y1: float) -> bool:
    return x0 <= x <= x1 and y0 <= y <= y1


def _monogram(x: float, y: float) -> bool:
    """Block "UH": strokes only, so both letters stay legible down to 16 px.

    No font file, no rasteriser, no dependency: four rectangles for the "U" and
    three for the "H". A real font would look softer, and would also mean
    shipping a licence and a binary to regenerate one 5 kB icon.
    """
    x0, y0, x1, y1 = GLYPH_BOX
    width = (x1 - x0 - GAP) / 2
    middle = (y0 + y1) / 2

    u0, u1 = x0, x0 + width
    if (
        _bar(x, y, u0, y0, u0 + STROKE, y1)  # left stem
        or _bar(x, y, u1 - STROKE, y0, u1, y1)  # right stem
        or _bar(x, y, u0, y1 - STROKE, u1, y1)  # bowl
    ):
        return True

    h0, h1 = x1 - width, x1
    return bool(
        _bar(x, y, h0, y0, h0 + STROKE, y1)  # left stem
        or _bar(x, y, h1 - STROKE, y0, h1, y1)  # right stem
        or _bar(x, y, h0, middle - STROKE / 2, h1, middle + STROKE / 2)  # crossbar
    )


def _inside_tile(x: float, y: float, radius: float = 0.22) -> bool:
    """Rounded square in unit coordinates: the icon's ink tile."""
    if not (0.0 <= x <= 1.0 and 0.0 <= y <= 1.0):
        return False
    corner_x = radius if x < radius else (1 - radius if x > 1 - radius else None)
    corner_y = radius if y < radius else (1 - radius if y > 1 - radius else None)
    if corner_x is None or corner_y is None:
        return True  # not in a corner quadrant: inside by construction
    dx = x - corner_x
    dy = y - corner_y
    return dx * dx + dy * dy <= radius * radius


def pixels(size: int = SIZE, samples: int = 4) -> bytes:
    """RGBA pixels: ink tile, vertical gradient, gold "UH" with a drop shadow.

    Supersampled (``samples`` x ``samples`` per pixel): a four-stroke monogram
    needs anti-aliased edges, and downscaled hard edges are what makes a
    generated icon look cheap.
    """
    top = _blend(INK_RGB, 0.22)
    bottom = _blend(INK_RGB, -0.30)
    out = bytearray()
    step = 1.0 / samples
    span = max(1, size - 1)
    for py in range(size):
        for px in range(size):
            tile = 0
            glyph = 0
            shadow = 0
            for sy in range(samples):
                for sx in range(samples):
                    x = (px + (sx + 0.5) * step) / size
                    y = (py + (sy + 0.5) * step) / size
                    if not _inside_tile(x, y):
                        continue
                    tile += 1
                    if _monogram(x, y):
                        glyph += 1
                    elif _monogram(x, y - 0.012):
                        shadow += 1
            total = samples * samples
            if tile == 0:
                out += b"\x00\x00\x00\x00"
                continue
            colour = _mix(top, bottom, py / span)
            if shadow:
                colour = _mix(colour, _blend(colour, -0.60), shadow / total)
            if glyph:
                colour = _mix(colour, ACCENT_RGB, glyph / total)
            alpha = int(round(255 * tile / total))
            out += bytes((colour[0], colour[1], colour[2], alpha))
    return bytes(out)


def _chunk(kind: bytes, payload: bytes) -> bytes:
    return (
        struct.pack(">I", len(payload))
        + kind
        + payload
        + struct.pack(">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)
    )


def png_bytes(size: int = SIZE) -> bytes:
    """A PNG for the icon: 8-bit RGBA, one filter byte per row, zlib-compressed."""
    raw = pixels(size)
    stride = size * 4
    rows = b"".join(b"\x00" + raw[y * stride : (y + 1) * stride] for y in range(size))
    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", header)
        + _chunk(b"IDAT", zlib.compress(rows, 9))
        + _chunk(b"IEND", b"")
    )


def icon_bytes(sizes: Sequence[int] = ICON_SIZES) -> bytes:
    """An ICO carrying one PNG entry per size: native for Windows 10+.

    PNG entries are legal in the ICO format and keep the file to a few kilobytes;
    a hand-rolled BMP (BGRA + AND mask) would be three times bigger for no
    visible gain.
    """
    pngs = [(size, png_bytes(size)) for size in sizes]
    offset = 6 + 16 * len(pngs)
    entries = bytearray()
    payload = bytearray()
    for size, png in pngs:
        width = 0 if size >= 256 else size  # 0 means 256, by the format
        entries += struct.pack("<BBBBHHII", width, width, 0, 0, 1, 32, len(png), offset)
        payload += png
        offset += len(png)
    return struct.pack("<HHH", 0, 1, len(pngs)) + bytes(entries) + bytes(payload)


# --------------------------------------------------------------------------- #
# writing
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class Install:
    """What ``install()`` produced, so the CLI can print it and tests can check it."""

    script: Path
    icon: Path
    link: Path


def write_launcher(directory: Path) -> tuple[Path, Path]:
    """Write ``uh-web.ps1`` and ``uh-web.ico`` into ``directory``."""
    directory.mkdir(parents=True, exist_ok=True)
    script = directory / SCRIPT_NAME
    icon = directory / ICON_NAME
    script.write_text(script_text(), encoding="ascii", newline="\r\n")
    icon.write_bytes(icon_bytes())
    return script, icon


def _ps_quote(value: str) -> str:
    """A PowerShell single-quoted literal (doubling the quote is the only escape)."""
    return "'" + value.replace("'", "''") + "'"


def link_command(link: Path, script: Path, icon: Path, workdir: Path) -> str:
    """The PowerShell that creates the ``.lnk``, printed by ``--dry-run``-ish tests."""
    arguments = f'-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{script}"'
    return "\n".join(
        [
            "$ErrorActionPreference = 'Stop'",
            "$shell = New-Object -ComObject WScript.Shell",
            f"$lnk = $shell.CreateShortcut({_ps_quote(str(link))})",
            f"$lnk.TargetPath = {_ps_quote(str(_powershell()))}",
            f"$lnk.Arguments = {_ps_quote(arguments)}",
            f"$lnk.WorkingDirectory = {_ps_quote(str(workdir))}",
            f"$lnk.IconLocation = {_ps_quote(str(icon))}",
            f"$lnk.Description = {_ps_quote(LINK_DESCRIPTION)}",
            "$lnk.WindowStyle = 7",  # minimized: the browser is the window
            "$lnk.Save()",
            "$lnk.FullName",
            "",
        ]
    )


def run_powershell(script: str, timeout: float = 30.0) -> str:
    """Run ``script`` with powershell.exe, return stdout. Raises ShortcutError."""
    command: Sequence[str] = [
        str(_powershell()),
        "-NoLogo",
        "-NoProfile",
        "-NonInteractive",
        "-ExecutionPolicy",
        "Bypass",
        "-Command",
        script,
    ]
    try:
        completed = subprocess.run(
            list(command),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise ShortcutError(f"cannot run powershell.exe ({type(exc).__name__}: {exc})") from exc
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip().splitlines()
        reason = detail[-1] if detail else f"exit {completed.returncode}"
        raise ShortcutError(f"powershell failed: {reason}")
    return completed.stdout


def install(
    *,
    directory: Optional[Path] = None,
    desktop: Optional[Path] = None,
    runner: Optional[Runner] = None,
) -> Install:
    """Write the launcher and icon, then create the desktop shortcut.

    Nothing is written outside ``$UH_HOME`` and the Desktop; no registry key, no
    startup entry, no elevation. A failure leaves the two files in place - they
    are harmless - and raises :class:`ShortcutError` with one readable line.
    """
    target = directory or home_directory()
    desk = desktop or desktop_directory()
    script, icon = write_launcher(target)
    if not desk.is_dir():
        raise ShortcutError(f"no desktop folder at {desk}; set UH_DESKTOP to yours")
    link = desk / LINK_NAME
    command = link_command(link, script, icon, target)
    (runner or run_powershell)(command)
    if not link.is_file():
        raise ShortcutError(f"powershell reported success but {link} does not exist")
    return Install(script=script, icon=icon, link=link)


